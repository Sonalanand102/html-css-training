#  Tuple : A tuple is an ordered, immutable collection of elements in Python.

# Properties : 

# Ordered: Elements maintain their positions.

# Immutable: Elements cannot be reassigned or removed after creation.

# Allows duplicates: Duplicate values are allowed.

# Supports multiple data types: A tuple can contain different types of elements.

# Synatx : Tuples are created using patentheses ().

employee = (True,)

print(employee)

print(type(employee))