"""
Built-in data types in python.

1. Integer: int (Stores whole numbers without decimals points, e.g., 1, 2, 3)
2. Float: float (Stores numbers containing decimal points, e.g., 1.5, 2.7, 3.14)
3. String: str (Stores a sequence of characters or text, e.g., "Hello, World!")
4. Boolean: bool (Stores either True or False)
5. None: NoneType (Represents the absence of a value or a null value)

"""

#integer: int
print("Integer data type:")
age = 25

print(age)
print(type(age))

# Float: float
print("Float data type:")

price = 99.99

print(price)
print(type(price))

# String: str
print("String data type:")
name = "Sonal"  

print(name)
print(type(name))

# Boolean: bool
print("Boolean data type:")
is_student = True

print(is_student)
print(type(is_student))

# None: NoneType
print("None data type:")
result = None

print(result)
print(type(result))


