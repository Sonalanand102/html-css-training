"""
Indexing : Indexing means accessing an individual character from a string using its position.

Types of indexing:

1. Positive indexing
2. Negative indexing
"""  

word = "PYTHON"

# Positive indexing

print(word[0])
print(word[1])
print(word[2])
print(word[3])

# Negative indexing

print(word[-1])
print(word[-2])
print(word[-3])
print(word[-6])