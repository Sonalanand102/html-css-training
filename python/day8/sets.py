#Set:  A set is an unordered collection of unique elements.

# Properties : 

# Unique elements: Duplicate values are automatically removed.

# Unordered: Sets do not maintain a guaranteed positional order.

# Mutable: We can add and remove elements.

# No indexing: We cannot access elements using positions like set[0].

# Multiple data types: Sets can contain different hashable data types.

# Syntax : Sets are created using curly braces {} or the set() function.

